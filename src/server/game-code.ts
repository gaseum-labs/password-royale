import crypto from "node:crypto";

const codeCharacters = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
const splitCharacters = ["ABCDEFGH", "JKLMNPQR", "STUVWXYZ", "23456789"];

export const intToGameCode = (i: number): string => {
  const random = crypto.randomBytes(1);
  return (
    codeCharacters[i >>> 27] +
    codeCharacters[(i >>> 22) & 0x1f] +
    codeCharacters[(i >>> 17) & 0x1f] +
    codeCharacters[(i >>> 12) & 0x1f] +
    codeCharacters[(i >>> 7) & 0x1f] +
    codeCharacters[(i >>> 2) & 0x1f] +
    splitCharacters[i & 0x3][random[0] % 8]
  );
};

const makeMap = (size: number) => {
  const numbers: number[] = Array.from(new Array(size), (_, i) => i);

  for (let k = 0; k < 4; ++k) {
    const arr = new Uint32Array(size);
    const randomBytes = crypto.getRandomValues(arr);

    for (let i = 0; i < size; ++i) {
      let j = randomBytes[i] % size;
      const temp = numbers[i];
      numbers[i] = numbers[j];
      numbers[j] = temp;
    }
  }

  return numbers;
};

const genMapper = (size: number): ((i: number) => number) => {
  const lines: string[] = [];

  const numParts = 32 / size;

  const maps = Array.from(new Array(numParts), (_, i) => makeMap(1 << size));
  lines.push(`const maps = ${JSON.stringify(maps)};`);

  for (let i = 0; i < numParts; ++i) {
    lines.push(
      `const a${i} = maps[${i}][(i >>> ${i * size}) & ${(1 << size) - 1}];`,
    );
  }

  const scrambleMap = makeMap(numParts);
  lines.push(
    `return ${scrambleMap.map((mappedI, i) => `(a${mappedI} << ${i * size})`).join("|")};`,
  );

  return Function("i", lines.join("\n")) as (i: number) => number;
};

